const {chromium} = require('playwright');
const {spawn} = require('node:child_process');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const child = spawn(process.env.PANE_TEST_PYTHON || 'python', ['tests/browser_preview.py'], {stdio:['ignore','pipe','pipe']});
  let browser, logs='', previewUrl;
  child.stderr.on('data', data => logs+=data);
  try {
    await new Promise((resolve,reject) => {
      const timer=setTimeout(()=>reject(new Error('Preview not ready: '+logs)),10000);
      child.stdout.once('data',data=>{previewUrl=data.toString().trim().split(' ').at(-1);clearTimeout(timer);resolve();});
      child.once('exit',code=>{clearTimeout(timer);reject(new Error('Preview exited '+code+': '+logs));});
    });
    browser=await chromium.launch({executablePath:process.env.PANE_TEST_CHROMIUM || undefined, headless:true, args:['--no-sandbox']});
    const page=await browser.newPage({viewport:{width:1100,height:950}});
    const errors=[]; page.on('pageerror', error=>{errors.push(error.message);console.error(error.message);});
    await page.goto(previewUrl);
    await page.evaluate(()=>{localStorage.setItem('handset-transport','wifi');localStorage.removeItem('pane-state-schema');});
    await page.reload();
    await page.locator('#onboarding').waitFor({state:'visible'});
    assert.equal(await page.locator('#onboarding-next').isDisabled(),true);
    await page.route('**/api/setup',route=>route.fulfill({json:{phase:'idle',note:'Trust this phone',onboardingRequired:false,boundUdid:'saved-phone'}}));
    await page.locator('#onboarding').waitFor({state:'hidden'});
    await page.locator('#feature-tour').waitFor({state:'visible'});
    await page.locator('#tour-skip').click();
    await page.getByRole('button',{name:'Connect your iPhone',exact:false}).click();
    await page.locator('#run-guide').waitFor({state:'visible'});
    await page.waitForFunction(()=>document.querySelector('#setup-progress').textContent.includes('Trust'));
    assert.equal(await page.evaluate(()=>localStorage.getItem('handset-transport')),'wifi');
    assert.equal(await page.locator('[data-setup="start"]').isDisabled(),true);
    assert.equal(await page.locator('[data-btn="volume-up"]').count(),2);
    await page.getByRole('tab',{name:'Uploads',exact:true}).click();
    assert.equal(await page.locator('#uploads-panel').isVisible(),true);
    assert.equal(await page.locator('#connection-panel').isVisible(),false);
    await page.getByRole('tab',{name:'Uploads',exact:true}).press('ArrowLeft');
    assert.equal(await page.locator('#connection-tab').getAttribute('aria-selected'),'true');
    await page.getByRole('tab',{name:'Connection',exact:true}).press('End');
    assert.equal(await page.locator('#settings-tab').getAttribute('aria-selected'),'true');
    await page.getByRole('tab',{name:'Uploads',exact:true}).click();
    assert.ok(await page.locator('.drawer-scroll').evaluate(el=>el.scrollWidth <= el.clientWidth));
    await page.locator('#outgoing-files').setInputFiles({name:'hello.txt',mimeType:'text/plain',buffer:Buffer.from('hello iPhone')});
    await page.getByText('1 file(s) queued.',{exact:false}).waitFor();
    await page.locator('.transfer strong').filter({hasText:'hello.txt'}).waitFor();
    assert.match(await page.locator('.transfer').innerText(),/To iPhone/);
    assert.equal(await page.locator('.transfer-state').innerText(),'Queued');
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.transfer').textContent.includes('Cancelled'));
    fs.mkdirSync('test-results',{recursive:true});
    await page.screenshot({path:'test-results/uploads.png'});
    await page.getByRole('tab',{name:'Connection',exact:true}).click();
    const requests=[];
    await page.route('**/api/setup/*', route=>{requests.push({path:new URL(route.request().url()).pathname,...route.request().postDataJSON()});return route.fulfill({json:{phase:'waiting',step:'developer',note:'Enable Developer Mode on your iPhone.'}});});
    await page.route('**/api/status',route=>route.fulfill({json:{driver:{ready:true},library:{ready:true},devices:[{udid:'test-phone',connection:'USB',deviceId:1}],developerMode:false,screen:{phase:'idle'},wifi:{paired:[]}}}));
    await page.route('**/api/devices/**',route=>route.fulfill({json:{paired:true,info:{DeviceName:'Test iPhone'}}}));
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>!document.querySelector('[data-setup="start"]').disabled);
    await page.locator('#toggle-guide').click();
    await page.locator('[data-setup="start"]').click();
    assert.equal(requests[0].path,'/api/setup/start');
    assert.equal(requests[0].udid,'test-phone');
    await page.locator('#run-guide details').filter({has:page.locator(':scope > summary',{hasText:'Install Pane'})}).locator(':scope > summary').click();
    await page.locator('.altstore-guide > summary').click();
    assert.match(await page.locator('.altstore-guide').innerText(), /Apple Account/);
    await page.screenshot({path:'test-results/setup.png'});
    let signingView={phase:'idle',available:true,note:'Ready'};
    await page.route('**/api/signing',route=>route.fulfill({json:signingView}));
    const signRequests=[];
    await page.route('**/api/signing/*',route=>{
      signRequests.push({path:new URL(route.request().url()).pathname,...route.request().postDataJSON()});
      signingView={phase:'prompt',available:true,note:'Enter code',prompt:{id:'prompt-one',kind:'verification',choices:[]}};
      return route.fulfill({json:signingView});
    });
    await page.locator('#signing-email').fill('test@example.com');
    assert.match(await page.locator('#signing-privacy').innerText(), /processed locally by Pane and its signing helper/);
    assert.match(await page.locator('#signing-privacy').innerText(), /does not save your password/);
    assert.match(await page.locator('#signing-privacy').innerText(), /ani\.iloader\.app/);
    await page.locator('#signing-password').fill('test-only-password');
    await page.locator('.signing-options summary').click();
    await page.locator('#signing-ipa').setInputFiles({name:'Pane.ipa',mimeType:'application/octet-stream',buffer:Buffer.from('test unsigned ipa')});
    await page.waitForFunction(()=>!document.querySelector('#signing-start').disabled);
    await page.locator('#signing-start').click();
    await page.locator('#signing-prompt').waitFor({state:'visible'});
    assert.equal(signRequests[0].password,'test-only-password');
    assert.equal(signRequests[0].udid,'test-phone');
    assert.equal(await page.locator('#signing-password').inputValue(),'');
    await page.locator('#signing-code').fill('123456');
    await page.locator('#signing-answer').click();
    await page.waitForTimeout(50);
    assert.equal(signRequests[1].promptId,'prompt-one');
    assert.equal(signRequests[1].value,'123456');
    // First-install journey advances only after backend/device confirmation.
    await page.evaluate(()=>postJson('/api/preferences',{tour_complete:false}));
    const wizard=await browser.newPage({viewport:{width:470,height:860}});
    wizard.on('pageerror',error=>{errors.push(error.message);console.error(error.message);});
    let setup={phase:'idle',onboardingRequired:true,note:'Connect your iPhone'};
    let ble={phase:'idle',note:'Waiting for companion'};
    let enabled=false, attempts=0, plugged=false;
    const actions=[];
    await wizard.route('**/api/status',r=>r.fulfill({json:{driver:{ready:true},library:{ready:true},devices:plugged?[{udid:'wizard-phone',name:'My iPhone',connection:'USB',deviceId:1}]:[],screen:{phase:'idle'},wifi:{paired:[]}}}));
    await wizard.route('**/api/devices/**',r=>r.fulfill({json:{paired:true,info:{DeviceName:'My iPhone'}}}));
    await wizard.route('**/api/setup',r=>r.fulfill({json:setup}));
    await wizard.route('**/api/uploads',r=>r.fulfill({json:{bluetooth:ble,transfers:[],destination:'Downloads'}}));
    await wizard.route('**/api/signing',r=>r.fulfill({json:{phase:'idle',available:true,note:'Ready'}}));
    await wizard.route('**/api/screen',r=>r.fulfill({json:{phase:'idle'}}));
    await wizard.route('**/api/setup/*',r=>{
      const action=new URL(r.request().url()).pathname.split('/').pop();actions.push(action);
      assert.equal(r.request().postDataJSON().udid,'wizard-phone');
      setup={...setup,udid:'wizard-phone',error:null};
      if(action==='start')setup={...setup,usbReady:true,revealed:true,phase:'waiting'};
      if(action==='developer')setup=enabled?{...setup,developerEnabled:true,phase:'ready'}:{...setup,phase:'error',error:'Developer Mode is not enabled yet.'};
      if(action==='bind')setup={...setup,boundUdid:'wizard-phone',wifiBound:true,phase:'waiting'};
      return r.fulfill({json:setup});
    });
    await wizard.route('**/api/signing/start',r=>{
      assert.equal(r.request().postDataJSON().udid,'wizard-phone');
      actions.push('install');setup={...setup,installed:true,phase:'ready'};
      return r.fulfill({json:{phase:'complete',available:true,note:'Installed'}});
    });
    await wizard.route('**/api/bluetooth/connect',r=>{
      attempts++;
      ble=attempts===1?{phase:'error',note:'Open Pane on your iPhone, then retry.'}:{phase:'connected',note:'Connected'};
      if(attempts>1)setup={...setup,onboardingRequired:false};
      return r.fulfill({json:ble});
    });
    await wizard.goto(previewUrl);
    await wizard.locator('#onboarding').waitFor({state:'visible'});
    assert.equal(await wizard.locator('#onboarding-next').isDisabled(),true);
    plugged=true;
    await wizard.locator('#onboarding-refresh').click();
    await wizard.waitForFunction(()=>!document.querySelector('#onboarding-next').disabled);
    await wizard.screenshot({path:'test-results/first-run.png'});
    await wizard.locator('#onboarding-next').click();
    await wizard.getByRole('heading',{name:'Enable Developer Mode',exact:true}).waitFor();
    assert.match(await wizard.locator('#onboarding-developer').innerText(), /Check Developer Mode to request the option again/);
    await wizard.locator('#onboarding-next').click();
    await wizard.getByText('Developer Mode is not enabled yet.',{exact:true}).first().waitFor();
    assert.equal(await wizard.locator('#onboarding-signing').isVisible(),false);
    enabled=true;
    await wizard.locator('#onboarding-next').click();
    await wizard.locator('#onboarding-signing').waitFor({state:'visible'});
    assert.equal(await wizard.locator('#signing-privacy').isVisible(), true);
    plugged=false;
    await wizard.waitForFunction(()=>document.querySelector('#signing-start').disabled);
    await wizard.getByText('Connect your unlocked iPhone by USB to enable installation.',{exact:false}).waitFor();
    plugged=true;
    await wizard.waitForFunction(()=>!document.querySelector('#signing-start').disabled);
    await wizard.locator('#signing-email').fill('test@example.com');
    await wizard.locator('#signing-password').fill('test-only-password');
    await wizard.screenshot({path:'test-results/first-run-install.png'});
    await wizard.locator('#signing-start').click();
    await wizard.getByRole('heading',{name:'Open Pane on iPhone',exact:true}).waitFor();
    await wizard.waitForFunction(()=>document.querySelector('#onboarding-note').textContent.includes('retry'));
    assert.equal(attempts,1,'Bluetooth failure must not loop');
    await wizard.locator('#onboarding-next').click();
    await wizard.locator('#onboarding').waitFor({state:'hidden'});
    await wizard.locator('#feature-tour').waitFor({state:'visible'});
    await wizard.locator('#tour-next').click();
    await wizard.locator('#tour-next').click();
    await wizard.locator('#tour-next').click();
    await wizard.locator('#feature-tour').waitFor({state:'hidden'});
    assert.deepEqual(actions,['start','developer','developer','install','bind']);
    await wizard.reload();
    await wizard.waitForFunction(()=>document.querySelector('#setup-progress').textContent.includes('Connected'));
    assert.equal(await wizard.locator('#onboarding').isVisible(),false,'paired installations skip first-run setup');
    assert.equal(attempts,2);
    await wizard.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: preserved preferences, retained volume buttons, setup request, AltStore guidance, Uploads tab, real staging/cancellation, no browser errors.');
  } finally { if(browser)await browser.close(); child.kill(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
